-- Registro de conversaciones del broadcast por (teléfono cliente, número Infobip).
-- Ejecutar una sola vez en Supabase → SQL Editor (después de infobip_ext_broadcast.sql).
--
-- Estados: CREANDO (reserva mientras se crea en Infobip) → ACTIVA → CERRADA.
-- El índice único parcial garantiza UNA sola conversación no cerrada por par:
-- si dos broadcasts llegan a la vez al mismo contacto, solo uno puede crearla.

create table if not exists "Infobip_ext".broadcast_conversacion (
  id              bigint generated by default as identity primary key,
  telefono        text        not null,
  sender          text        not null,
  conversation_id text        unique,
  estado          text        not null check (estado in ('CREANDO', 'ACTIVA', 'CERRADA')),
  -- BROADCAST: la creó el broadcast. VENTA_ACTIVA: venía de conversation_lead_relation.
  origen          text        not null default 'BROADCAST',
  queue_id        text,
  broadcast_id    bigint,
  created_at      timestamptz not null default now(),
  updated_at      timestamptz not null default now(),
  cerrada_at      timestamptz
);

create unique index if not exists broadcast_conversacion_par_activo_uidx
  on "Infobip_ext".broadcast_conversacion (telefono, sender)
  where estado <> 'CERRADA';

create index if not exists broadcast_conversacion_par_idx
  on "Infobip_ext".broadcast_conversacion (telefono, sender);

alter table "Infobip_ext".broadcast_conversacion enable row level security;
grant all on "Infobip_ext".broadcast_conversacion to service_role;
grant usage, select on all sequences in schema "Infobip_ext" to service_role;

-- Conversaciones que ya creó el broadcast antes de esta tabla (última por par).
insert into "Infobip_ext".broadcast_conversacion (telefono, sender, conversation_id, estado, broadcast_id)
select distinct on (d.telefono, b.sender)
  d.telefono, b.sender, d.conversation_id, 'ACTIVA', b.id
from "Infobip_ext".broadcast_destinatario d
join "Infobip_ext".broadcast b on b.id = d.broadcast_id
where d.estado = 'OK' and d.conversation_id is not null
order by d.telefono, b.sender, d.updated_at desc
on conflict do nothing;
