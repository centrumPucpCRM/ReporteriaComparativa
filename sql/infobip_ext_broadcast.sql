-- Broadcast de plantillas WhatsApp (Reportería → Infobip CCaaS).
-- Ejecutar una sola vez en Supabase → SQL Editor.
--
-- broadcast:              un envío masivo (quién, cola, asesor, línea, plantilla).
-- broadcast_destinatario: una fila por teléfono, con su estado de envío.
--   Estados: PENDIENTE → ENVIANDO → OK | ERROR.
--   ERROR significa que la plantilla NO salió (se puede reintentar sin duplicar).
--   ENVIANDO que quede colgado = el envío se cortó a mitad: revisar a mano en Infobip.

create table if not exists "Infobip_ext".broadcast (
  id                 bigint generated by default as identity primary key,
  created_at         timestamptz not null default now(),
  updated_at         timestamptz not null default now(),
  creado_por         text,
  campana            text        not null,
  queue_id           text        not null,
  queue_nombre       text,
  agent_id           text,
  agent_nombre       text,
  sender             text        not null,
  template_nombre    text        not null,
  template_idioma    text        not null,
  template_variables int[]       not null default '{}',
  -- Cómo se llenó cada {{n}}: {"1": {"tipo": "columna", "columna": "nombre"}, "2": {"tipo": "fijo", "valor": "MBA"}}
  mapeo              jsonb,
  total              int         not null default 0,
  enviados           int         not null default 0,
  fallidos           int         not null default 0,
  -- EN_CURSO | FINALIZADO
  estado             text        not null default 'EN_CURSO'
);

create table if not exists "Infobip_ext".broadcast_destinatario (
  id                       bigint generated by default as identity primary key,
  broadcast_id             bigint      not null references "Infobip_ext".broadcast(id) on delete cascade,
  fila                     int         not null,
  telefono                 text        not null,
  -- {"{{1}}": "Ana", "{{2}}": "MBA"}
  parametros               jsonb       not null default '{}'::jsonb,
  estado                   text        not null default 'PENDIENTE'
                           check (estado in ('PENDIENTE', 'ENVIANDO', 'OK', 'ERROR')),
  conversation_id          text,
  conversacion_reutilizada boolean,
  error                    text,
  advertencia              text,
  created_at               timestamptz not null default now(),
  updated_at               timestamptz not null default now(),
  unique (broadcast_id, telefono)
);

create index if not exists broadcast_destinatario_broadcast_estado_idx
  on "Infobip_ext".broadcast_destinatario (broadcast_id, estado);

-- La reutilización de conversaciones busca por (telefono_contacto, sender).
create index if not exists conversation_lead_relation_tel_sender_idx
  on "Infobip_ext".conversation_lead_relation (telefono_contacto, sender);

-- Solo el service role (server actions) toca estas tablas; anon/authenticated no.
alter table "Infobip_ext".broadcast enable row level security;
alter table "Infobip_ext".broadcast_destinatario enable row level security;

grant all on "Infobip_ext".broadcast, "Infobip_ext".broadcast_destinatario to service_role;
grant usage, select on all sequences in schema "Infobip_ext" to service_role;
