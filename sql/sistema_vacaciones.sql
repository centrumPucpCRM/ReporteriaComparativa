-- Sistema de Vacaciones: periodos programados por vendedor.
-- Ejecutar una sola vez en Supabase → SQL Editor, y luego agregar "Sistema_vacaciones"
-- en Settings → API → Exposed schemas.
--
-- periodo: unas vacaciones con fechas (días completos, hora Lima).
--   Estados: PROGRAMADA → EN_CURSO → FINALIZADA, o PROGRAMADA → CANCELADA.
--   La sincronización (cron diario + cada cambio en la UI) marca CTREnVacaciones_c = true
--   en Oracle al pasar a EN_CURSO y false al pasar a FINALIZADA.
--   error: último fallo al escribir en Oracle (el periodo no cambia de estado y se reintenta).

create schema if not exists "Sistema_vacaciones";

-- Necesaria para el exclude de solapamiento (= sobre texto dentro de un índice gist).
create extension if not exists btree_gist with schema extensions;

create table if not exists "Sistema_vacaciones".periodo (
  id               bigint generated by default as identity primary key,
  party_number     text        not null,
  vendedor_nombre  text        not null,
  vendedor_correo  text,
  fecha_inicio     date        not null,
  fecha_fin        date        not null,
  nota             text,
  estado           text        not null default 'PROGRAMADA'
                   check (estado in ('PROGRAMADA', 'EN_CURSO', 'FINALIZADA', 'CANCELADA')),
  error            text,
  creado_por       text,
  actualizado_por  text,
  created_at       timestamptz not null default now(),
  updated_at       timestamptz not null default now(),
  check (fecha_fin >= fecha_inicio),
  -- Un vendedor no puede tener dos periodos vigentes que se crucen.
  constraint periodo_sin_solapamiento exclude using gist (
    party_number with =,
    daterange(fecha_inicio, fecha_fin, '[]') with &&
  ) where (estado <> 'CANCELADA')
);

create index if not exists periodo_fechas_idx on "Sistema_vacaciones".periodo (fecha_inicio, fecha_fin);
create index if not exists periodo_estado_idx on "Sistema_vacaciones".periodo (estado);

-- Solo el service role (server actions y cron) toca estas tablas; anon/authenticated no.
alter table "Sistema_vacaciones".periodo enable row level security;

grant usage on schema "Sistema_vacaciones" to service_role;
grant all on "Sistema_vacaciones".periodo to service_role;
grant usage, select on all sequences in schema "Sistema_vacaciones" to service_role;
