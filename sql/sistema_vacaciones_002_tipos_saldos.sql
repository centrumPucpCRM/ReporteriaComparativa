create table if not exists "Sistema_vacaciones".saldo (
  party_number       text        not null,
  anio               int         not null,
  dias_asignados     numeric     not null check (dias_asignados >= 0),
  dias_transferidos  numeric     not null default 0,
  nota               text,
  actualizado_por    text,
  updated_at         timestamptz not null default now(),
  primary key (party_number, anio)
);

create table if not exists "Sistema_vacaciones".configuracion (
  id                  int primary key default 1 check (id = 1),
  -- 0 = lunes … 6 = domingo
  dias_laborales      int[]       not null default '{0,1,2,3,4}',
  dias_por_anio       numeric     not null default 30 check (dias_por_anio >= 0),
  -- INMEDIATO: todo el año disponible desde el 1 de enero. MENSUAL: 1/12 por mes cumplido.
  metodo_adquisicion  text        not null default 'INMEDIATO' check (metodo_adquisicion in ('INMEDIATO', 'MENSUAL')),
  actualizado_por     text,
  updated_at          timestamptz not null default now()
);
