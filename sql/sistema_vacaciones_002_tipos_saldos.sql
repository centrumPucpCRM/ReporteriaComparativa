-- Sistema de Vacaciones (2): tipos de ausencia, feriados, saldos por año y configuración.
-- Ejecutar en Supabase → SQL Editor DESPUÉS de sistema_vacaciones.sql. Es idempotente.
--
-- tipo: catálogo de ausencias (Vacaciones, Descanso médico, Licencia…).
--   conteo: CALENDARIO (todos los días) o LABORAL (sin días no laborables ni feriados).
--   descuenta_saldo: los días se restan del saldo anual del vendedor.
--   permite_saldo_negativo: si no, no se puede programar más de lo que le queda.
--   motivo_requerido: la nota es obligatoria al programar.
--   marca_oracle: mientras dure, CTREnVacaciones_c = true en Oracle (no recibe leads).
-- feriado: días no laborables para el conteo LABORAL y para el Horario.
-- saldo: días asignados y transferidos (del año anterior) por vendedor y año; si no hay
--   fila se usan los días por año de la configuración y 0 transferidos.
-- configuracion: una sola fila (id = 1).

create table if not exists "Sistema_vacaciones".tipo (
  id                      bigint generated by default as identity primary key,
  codigo                  text        not null unique,
  nombre                  text        not null,
  color                   text        not null default '#10b981',
  activo                  boolean     not null default true,
  conteo                  text        not null default 'CALENDARIO' check (conteo in ('CALENDARIO', 'LABORAL')),
  descuenta_saldo         boolean     not null default false,
  permite_saldo_negativo  boolean     not null default false,
  motivo_requerido        boolean     not null default false,
  marca_oracle            boolean     not null default true,
  orden                   int         not null default 0,
  created_at              timestamptz not null default now(),
  updated_at              timestamptz not null default now()
);

