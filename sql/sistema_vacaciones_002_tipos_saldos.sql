on conflict (codigo) do nothing;

-- Los periodos existentes eran todos vacaciones.
alter table "Sistema_vacaciones".periodo
  add column if not exists tipo_id bigint references "Sistema_vacaciones".tipo (id);
update "Sistema_vacaciones".periodo
  set tipo_id = (select id from "Sistema_vacaciones".tipo where codigo = 'VAC')
  where tipo_id is null;
alter table "Sistema_vacaciones".periodo alter column tipo_id set not null;
create index if not exists periodo_tipo_idx on "Sistema_vacaciones".periodo (tipo_id);

create table if not exists "Sistema_vacaciones".feriado (
  fecha       date primary key,
  nombre      text        not null,
  created_at  timestamptz not null default now()
);

